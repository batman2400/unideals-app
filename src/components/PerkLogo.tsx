function rasterLogo(url: string | null | undefined): string | null {
  const remote = url?.trim() ?? "";
  if (!/^https:\/\//i.test(remote)) return null;
  if (/\.svg(?:$|\?)/i.test(remote) || remote.includes("/perk-logos/")) return null;
  return remote;
}

interface PerkLogoProps {
  providerName: string;
  logoUrl?: string | null;
  size?: number;
}

export function PerkLogo({ providerName, logoUrl, size = 40 }: PerkLogoProps) {
  const remote = rasterLogo(logoUrl);
  const mark = MARKS[providerName];
  const box = { width: size, height: size, borderRadius: radius.md };

  if (remote) {
    return <Image source={{ uri: remote }} style={[styles.box, box]} contentFit="contain" />;
  }

  if (!mark) {
    return (
      <View style={[styles.fallback, box]}>
        <Text style={[styles.letter, { fontSize: size * 0.4 }]}>
          {providerName.slice(0, 1).toUpperCase()}
        </Text>
      </View>
    );
  }

  const glyph = Math.round(size * 0.62);
  return (
    <View style={[styles.box, box]}>
      <Svg width={glyph} height={glyph} viewBox="0 0 24 24">
        <Path d={mark.d} fill={mark.fill} />
      </Svg>
    </View>
  );
}

const styles = StyleSheet.create({
  box: {
    alignItems: "center",
    justifyContent: "center",
    backgroundColor: colors.surfaceContainerLow,
  },
  fallback: {
    alignItems: "center",
    justifyContent: "center",
    backgroundColor: colors.primaryContainer,
  },
  letter: {
    fontWeight: "800",
    color: colors.onPrimaryContainer,
  },
});
